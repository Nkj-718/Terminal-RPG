    private void summonWeapon(Player player) {

        String weapon = player.getWeapon();

        System.out.println();

        switch (weapon) {

            case "Club":
                System.out.println("A heavy club forms in your hands.");
                System.out.println("Its weight feels strangely familiar.");
                break;

            case "Gauntlets":
                System.out.println("Bright Crimson gauntlets form around your fists.");
                System.out.println("You flex your fingers.");
                System.out.println("The metal moves as though it has always belonged to you.");
                break;

            case "Sword":
                System.out.println("A sword forms in your hands.");
                System.out.println("You don't remember ever holding one.");
                break;

            case "Spear":
                System.out.println("A spear forms in your hands.");
                System.out.println("You instinctively adjust your grip.");
                break;

            default:
                System.out.println("Something takes shape in your hands.");
                break;
        }
    }

